import { ethers } from "hardhat";
import * as fs from "fs";
import * as path from "path";

async function main() {
  const [deployer] = await ethers.getSigners();
  if (!deployer) {
    throw new Error("No deployer signer found. Please check your PRIVATE_KEY configuration in .env");
  }

  const network = await ethers.provider.getNetwork();
  const balance = await ethers.provider.getBalance(deployer.address);

  console.log("==================================================");
  console.log("Deploying SecureChain to MST Blockchain Testnet");
  console.log("==================================================");
  console.log(`Network Name:  ${network.name}`);
  console.log(`Chain ID:      ${network.chainId.toString()}`);
  console.log(`Deployer Addr: ${deployer.address}`);
  console.log(`Balance:       ${ethers.formatEther(balance)} tMSTC`);
  console.log("==================================================");

  if (balance === 0n) {
    console.warn("⚠️ Warning: Deployer balance is 0 tMSTC. Ensure you have testnet faucet funds.");
  }

  console.log("Deploying SecureChain contract...");
  const SecureChainFactory = await ethers.getContractFactory("SecureChain");
  const secureChain = await SecureChainFactory.deploy();
  await secureChain.waitForDeployment();

  const deployedAddress = await secureChain.getAddress();
  const deploymentTx = secureChain.deploymentTransaction();

  console.log("✅ SecureChain successfully deployed!");
  console.log(`Contract Address: ${deployedAddress}`);
  if (deploymentTx) {
    console.log(`Deployment Tx:    ${deploymentTx.hash}`);
    console.log(`Explorer URL:     https://testnet.mstscan.com/tx/${deploymentTx.hash}`);
  }

  // Export contract address and ABI to frontend configuration directory
  const frontendConfigDir = path.join(__dirname, "../frontend/src/config");
  if (!fs.existsSync(frontendConfigDir)) {
    fs.mkdirSync(frontendConfigDir, { recursive: true });
  }

  const artifactPath = path.join(__dirname, "../artifacts/contracts/SecureChain.sol/SecureChain.json");
  if (fs.existsSync(artifactPath)) {
    const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf-8"));
    const configContent = `// Auto-generated by scripts/deploy.ts
export const SECURE_CHAIN_CONTRACT_ADDRESS = "${deployedAddress}";
export const SECURE_CHAIN_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
    fs.writeFileSync(path.join(frontendConfigDir, "contractConfig.ts"), configContent);
    console.log(`Saved contract address & ABI to frontend/src/config/contractConfig.ts`);
  }
}

main().catch((error) => {
  console.error("Deployment failed:", error);
  process.exit(1);
});
